"""Step 3.5t: read the slow take-off probe's rows (`slow-take-off.ts`).

    python3 docs/research/new-rider/3.5/slow-take-off.py results/35t/catch    # c-<script>-<run>.jsonl[.gz]
    python3 docs/research/new-rider/3.5/slow-take-off.py results/35t/organic  # o-s<seed>.jsonl[.gz]

Every median is a plain median; every time is seconds after the stand (the first `standing` frame) unless named.
A censored stand counts at its floor and is printed `>=`.
"""
import glob
import gzip
import json
import os
import statistics as st
import sys

D = sys.argv[1]
ARM = sys.argv[2] if len(sys.argv) > 2 else ''  # a file prefix suffix, e.g. '-slow' for c-cue-slow-0.jsonl


def load(path):
    rows, meta = [], {}
    for line in (gzip.open(path, 'rt') if path.endswith('.gz') else open(path)):
        x = json.loads(line)
        k = x.get('kind')
        if k == 'f':
            rows.append(x)
        elif k in ('summary', 'stand', 'control', 'built'):
            meta.setdefault(k, []).append(x)
    return rows, meta


def med(v):
    v = [x for x in v if x is not None]
    return st.median(v) if v else None


def fmt(x, n=2):
    return '—' if x is None else f'{x:.{n}f}'


stands = []  # one dict per stand: source, id, script, outcome, frames
for path in sorted(glob.glob(os.path.join(D, f'c-cue*{ARM}-[0-9]*.jsonl*'))):
    name = os.path.basename(path).split('.jsonl')[0]
    parts = name.split('-')
    script, run = parts[1], int(parts[-1])
    rows, meta = load(path)
    s = meta['summary'][0]
    if s['stand'] is None:
        continue
    stands.append(dict(src='catch', id=f'r{run}', script=script, rows=rows, s=s, refusal=meta['stand'][0]['refusal']))
for path in sorted(glob.glob(os.path.join(D, f'o-s[0-9]{ARM}.jsonl*'))):
    seed = os.path.basename(path)[3]
    rows, meta = load(path)
    for s in meta.get('summary', []):
        if s['stand'] is None:
            continue
        rr = [x for x in rows if x['script'] == s['script'] and x['wave'] == s['wave']]
        ref = [x for x in meta['stand'] if x['script'] == s['script'] and x['wave'] == s['wave']]
        stands.append(dict(src=f'o{seed}', id=f"s{seed}w{s['wave']}", script=s['script'], rows=rr, s=s, refusal=ref[0]['refusal'] if ref else None))

for x in stands:
    s = x['s']
    x['fell'] = s['fellAfterStand']
    x['life'] = s['fellAfterStand'] if s['fellAfterStand'] is not None else (s.get('exposure') or 3.0)
    x['cens'] = s['fellAfterStand'] is None
    x['group'] = 'short' if (not x['cens'] and x['fell'] <= 1.2) else ('carried' if x['cens'] else 'mid')
    st_rows = [r for r in x['rows'] if r['tS'] is not None]
    x['standing'] = st_rows
    x['pre'] = [r for r in x['rows'] if r['tS'] is None]


def at(x, t):
    """The standing row nearest `t` s after the stand (None if the rider was gone)."""
    best = None
    for r in x['standing']:
        if r['tS'] <= t + 1e-6:
            best = r
    if best is None or (not x['cens'] and t > x['life'] + 1e-6):
        return None
    return best


def pre_at(x, which):
    pre = x['pre']
    cue = x['s']['cue']
    pop = x['s']['pop']
    stand = x['s']['stand']
    if which == 'cue':
        c = [r for r in pre if r['t'] >= cue - 1e-6]
        return c[0] if c else None
    if which == 'pop':
        c = [r for r in pre if r['t'] >= pop - 1e-6]
        return c[0] if c else None
    if which == 'stand':
        return x['standing'][0] if x['standing'] else None


COLS = ['vG', 'vW', 'plan', 'cap', 'ask', 'legBw', 'footF', 'footR', 'wet', 'subL', 'Fb', 'Fp', 'Fam', 'pitch', 'nose', 'tail',
        'fall', 'faceFrac', 'ahead', 'headZ', 'headX', 'copZ', 'capZ', 'capX', 'margin', 'ank', 'ref', 'hip', 'legRest']
MOMENTS = [('cue', None), ('pop', None), ('stand', 0.0), ('+0.25', 0.25), ('+0.5', 0.5), ('+0.75', 0.75), ('+1.0', 1.0)]

out = []
p = out.append
p('# 3.5t tables (generated by slow-take-off.py)\n')
p('## Stands\n')
p('| source | stand | script | refusal | after the stand, s | group | vW at stand | planing | Fp at stand | fall axis at the last frame |')
p('|---|---|---|---|---|---|---|---|---|---|')
for x in stands:
    last = x['standing'][-1] if x['standing'] else {}
    axis = '—'
    if not x['cens'] and last:
        pz, px = last.get('pastZ') or 0, last.get('pastX') or 0
        cz = last.get('capZ') or 0
        axis = ('along, ' + ('nose' if cz > 0 else 'tail')) if pz > px else ('across' if px > 0 else f'inside (capZ {cz:+.3f}, capX {last.get("capX", 0):+.3f})')
    st0 = x['standing'][0] if x['standing'] else {}
    life = f">= {x['life']:.3f}" if x['cens'] else f"{x['fell']:.3f}"
    p(f"| {x['src']} | {x['id']} | {x['script']} | {x['refusal']} | {life} | {x['group']} | {fmt(st0.get('vW'))} | {st0.get('plan')} | {fmt(st0.get('Fp'))} | {axis} |")

for script in ('cue', 'cueC'):
    grp = {g: [x for x in stands if x['script'] == script and x['group'] == g] for g in ('short', 'mid', 'carried')}
    p(f"\n## Medians by group, script `{script}` (short: fell <= 1.2 s, n {len(grp['short'])}; mid: 1.2-3 s, n {len(grp['mid'])}; carried: >= 3 s, n {len(grp['carried'])})\n")
    p('| moment | column | short | mid | carried | short range | carried range |')
    p('|---|---|---|---|---|---|---|')
    for label, t in MOMENTS:
        for c in COLS:
            vals = {}
            for g, xs in grp.items():
                v = []
                for x in xs:
                    r = pre_at(x, label) if t is None else at(x, t)
                    if r is not None and r.get(c) is not None:
                        v.append(r[c])
                vals[g] = v
            if not any(vals.values()):
                continue
            rng = lambda v: f'{min(v):.2f}..{max(v):.2f}' if v else '—'
            p(f"| {label} | {c} | {fmt(med(vals['short']))} | {fmt(med(vals['mid']))} | {fmt(med(vals['carried']))} | {rng(vals['short'])} | {rng(vals['carried'])} |")

# Separation: for each moment and column, the share of (short, carried) pairs ordered the same way (an AUC); 1 or 0 is a clean split.
p('\n## Separation, short against carried (both scripts pooled): AUC per column and moment (1.00 or 0.00 = no overlap)\n')
short = [x for x in stands if x['group'] == 'short']
carried = [x for x in stands if x['group'] == 'carried']
p(f'short n {len(short)}, carried n {len(carried)}\n')
p('| moment | ' + ' | '.join(COLS) + ' |')
p('|---|' + '---|' * len(COLS))
for label, t in MOMENTS:
    cells = []
    for c in COLS:
        a = [r[c] for x in short for r in [pre_at(x, label) if t is None else at(x, t)] if r is not None and r.get(c) is not None]
        b = [r[c] for x in carried for r in [pre_at(x, label) if t is None else at(x, t)] if r is not None and r.get(c) is not None]
        if not a or not b:
            cells.append('—')
            continue
        auc = sum((1 if u > v else 0.5 if u == v else 0) for u in a for v in b) / (len(a) * len(b))
        cells.append(f'{auc:.2f}')
    p(f'| {label} | ' + ' | '.join(cells) + ' |')

# The ledger: per source, the body's along-speed change and the board's pitch-rate change, summed over windows.
p('\n## The fore/aft ledger over the last 0.5 s before each fall (falls <= 1.2 s), medians over stands\n')
p('Along: the body\'s speed along its own forward axis relative to its carry, m/s, + toward the nose. Pitch: the board\'s pitch rate, rad/s, + noses DOWN.\n')
for script in ('cue', 'cueC'):
    xs = [x for x in stands if x['script'] == script and x['group'] == 'short']
    sums = {'along': {}, 'pitchDn': {}}
    for x in xs:
        acc = {'along': {}, 'pitchDn': {}}
        for r in x['standing']:
            if r['tS'] < x['life'] - 0.5 or 'led' not in r:
                continue
            for k in acc:
                for src, v in r['led'][k].items():
                    acc[k][src] = acc[k].get(src, 0) + v
        for k in acc:
            for src, v in acc[k].items():
                sums[k].setdefault(src, []).append(v)
    for k in sums:
        items = sorted(((src, med(v + [0] * (len(xs) - len(v)))) for src, v in sums[k].items()), key=lambda kv: -abs(kv[1]))
        p(f"- `{script}` {k} (n {len(xs)}): " + ', '.join(f'{src} {v:+.3f}' for src, v in items[:8]))
    closeA = max((r['led']['closeAlong'] for x in xs for r in x['standing'] if 'led' in r), default=None)
    closeP = max((r['led']['closePitch'] for x in xs for r in x['standing'] if 'led' in r), default=None)
    p(f'  - worst closure over these frames: along {closeA}, pitch {closeP}')

# Hull lift against the latch, every standing and landing frame of every stand, by speed through the water.
p('\n## The hull\'s vertical support against the planing latch, by speed through the water (standing frames, every stand)\n')
p('| vW, m/s | frames | latch on | Fp (dynamic pressure) / W | Fb (buoyancy) / W | Fam / W | wetted m² | pitch, deg | legBw |')
p('|---|---|---|---|---|---|---|---|---|')
bins = [(0, 2), (2, 3), (3, 3.5), (3.5, 4), (4, 4.5), (4.5, 5), (5, 6), (6, 8), (8, 20)]
allrows = [r for x in stands for r in x['standing']]
for lo, hi in bins:
    rr = [r for r in allrows if r['vW'] is not None and lo <= r['vW'] < hi]
    if not rr:
        continue
    p(f"| {lo}-{hi} | {len(rr)} | {sum(r['plan'] for r in rr) / len(rr):.2f} | {fmt(med([r['Fp'] for r in rr]))} | {fmt(med([r['Fb'] for r in rr]))} | {fmt(med([r['Fam'] for r in rr]))} | {fmt(med([r['wet'] for r in rr]), 3)} | {fmt(med([r['pitch'] for r in rr]), 1)} | {fmt(med([r['legBw'] for r in rr]))} |")

# Paddle past the cue (catch only).
p('\n## Paddling past the cue (catch, `paddle` script)\n')
p('| run | cue at, s | vW at cue | latch at cue | first vW >= 4.4 after the cue | first latch after the cue | max vW after cue | Fp/W at max | crest passed (ahead < -1.5) |')
p('|---|---|---|---|---|---|---|---|---|')
for path in sorted(glob.glob(os.path.join(D, f'c-paddle{ARM}-[0-9]*.jsonl*'))):
    rows, meta = load(path)
    s = meta['summary'][0]
    cue = s['cue']
    if cue is None:
        p(f"| {s['run']} | never | | | | | | | |")
        continue
    after = [r for r in rows if r['t'] >= cue - 1e-6]
    c0 = after[0]
    f44 = next((r['t'] - cue for r in after if r['vW'] >= 4.4), None)
    fpl = next((r['t'] - cue for r in after if r['plan'] == 1), None)
    mx = max(after, key=lambda r: r['vW'])
    p(f"| {s['run']} | {cue:.3f} | {c0['vW']:.2f} | {c0['plan']} | {fmt(f44)} | {fmt(fpl)} | {mx['vW']:.2f} (+{mx['t'] - cue:.2f} s) | {fmt(mx['Fp'])} | {fmt(None if s['passed'] is None else s['passed'] - cue)} |")

print('\n'.join(out))
